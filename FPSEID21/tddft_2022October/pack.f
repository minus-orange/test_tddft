      S(1,1,2)=1
      S(1,2,2)=1
      S(2,1,2)=-1
      S(1,2,3)=1
      S(2,1,3)=-1
      S(2,2,3)=-1
      S(1,1,4)=-1
      S(2,2,4)=-1
      S(1,1,5)=-1
      S(1,2,5)=-1
      S(2,1,5)=1
      S(1,2,6)=-1
      S(2,1,6)=1
      S(2,2,6)=1
      DO 41 I=2,6
   41 S(3,3,I)=1
      IF(PGIND.EQ.18) RETURN
      IF(PGIND.NE.19.AND.PGIND.NE.23) GO TO 45
C   POINT GROUP <6>.
      DO 42 KIND=2,6,2
      DO 42 J=1,3
      DO 42 I=1,3
   42 S(I,J,KIND)=-S(I,J,KIND)
      IF(PGIND.EQ.19) RETURN
C   POINT GROUP <6>M2 = C2Y(X)<6>.
      NTOT=12
