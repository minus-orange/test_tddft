   27 S(1,1,5)=1
      S(2,2,5)=-1
      S(3,3,5)=-1
   30 DO 32 KIND=2,4
      DO 32 J=1,3
      DO 32 I=1,3
      SUM=0
      DO 31 K=1,3
   31 SUM=SUM+S(I,K,5)*S(K,J,KIND)
   32 S(I,J,KIND+4)=SUM
      IF(PGIND.NE.17) RETURN
      NTOT=16
      DO 34 KIND=1,8
      DO 34 J=1,3
      DO 34 I=1,3
   34 S(I,J,KIND+8)=-S(I,J,KIND)
      RETURN
C   HERE FOR HEXAGONAL POINT GROUPS.
   40 IF(PGIND.GT.24) GO TO 60
      NTOT=6
