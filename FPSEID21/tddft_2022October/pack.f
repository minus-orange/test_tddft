      SUBROUTINE SMAT(PGIND,S,NTOT,IBRAV)
C********************************************************
      include 'mpif.h'
      INTEGER*4 S(3,3,48),PGIND,PIND(32)
      DATA PIND/1,1,3,4,5,6,6,8,9,8,11,12,11,14,15,16,14,18,19,18,21,
     1 22,23,21,25,26,25,28,28,30,31,30/
